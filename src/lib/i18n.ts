export const DICTS: Record<Locale, Dict> = { "zh-CN": ZH_CN, "zh-TW": ZH_TW, en: EN };

export type T = (key: Key, params?: Record<string, string | number>) => string;

/** 生成翻译函数:{x} 占位符替换;缺词条回落简体中文 */
export function makeT(locale: Locale): T {
  const d = DICTS[locale];
  return (key, params) => {
    let s = d[key] ?? ZH_CN[key] ?? String(key);
    if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

/** 资产名/单位词条:gold 需按数据源区分(沪金/伦敦金) */
export function assetLabel(key: AssetKey, goldSrc?: GoldSource): { name: Key; unit: Key } {
  if (key === "gold") {
    return goldSrc === "intl" ? { name: "goldIntlSrc", unit: "unitUsdOz" } : { name: "goldCnSrc", unit: "unitCnyG" };
  }
  const map: Record<"ndx" | "spx" | "dv50", { name: Key; unit: Key }> = {
    ndx: { name: "assetNdx", unit: "unitPoint" },
    spx: { name: "assetSpx", unit: "unitPoint" },
    dv50: { name: "assetDv50", unit: "unitCny" },
  };
  return map[key];
}
